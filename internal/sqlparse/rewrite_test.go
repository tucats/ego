func TestRewriteInsertOrIgnoreToPostgres(t *testing.T) {
	got, notes := mustRewrite(t, `INSERT OR IGNORE INTO t (id, name) VALUES (1, 'a')`, PostgreSQL, nil)

	if !strings.Contains(got, "ON CONFLICT") || !strings.Contains(got, "DO NOTHING") {
		t.Errorf("expected ON CONFLICT DO NOTHING, got:\n%s", got)
	}

	if strings.Contains(got, "OR IGNORE") {
		t.Errorf("expected OR IGNORE to be gone, got:\n%s", got)
	}

	if len(notes) == 0 {
		t.Errorf("expected a rewrite note")
	}
}

