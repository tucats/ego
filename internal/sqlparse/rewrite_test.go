func TestRewriteInsertOrReplaceToPostgres(t *testing.T) {
	lookup := func(table string) ([]string, error) {
		if table != "t" {
			t.Fatalf("unexpected table passed to lookup: %q", table)
		}

		return []string{"id"}, nil
	}

	got, notes := mustRewrite(t, `INSERT OR REPLACE INTO t (id, name, email) VALUES (1, 'a', 'a@example.com')`, PostgreSQL, lookup)

	if !strings.Contains(got, "ON CONFLICT (") || !strings.Contains(got, "\"id\"") {
		t.Errorf("expected ON CONFLICT (\"id\"), got:\n%s", got)
	}

	if !strings.Contains(got, "DO UPDATE SET") {
		t.Errorf("expected DO UPDATE SET, got:\n%s", got)
	}

	if !strings.Contains(got, "excluded") {
		t.Errorf("expected a reference to the excluded pseudo-table, got:\n%s", got)
	}

	if strings.Contains(got, `"EXCLUDED"`) {
		t.Errorf("expected the excluded pseudo-table reference to be lower-case (so PostgreSQL quoting still resolves it), got:\n%s", got)
	}

	if strings.Contains(got, "\"id\" = ") {
		t.Errorf("expected the key column not to appear in the SET list, got:\n%s", got)
	}

	if len(notes) == 0 {
		t.Errorf("expected a rewrite note")
	}
}

