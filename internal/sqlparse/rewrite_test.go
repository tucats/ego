func TestRewriteInsertOnConflictUnchangedOnBothDialects(t *testing.T) {
	// PostgreSQL-style ON CONFLICT is already valid sqlite3 (3.24+); Rewrite
	// must leave it alone in both directions.
	sql := `INSERT INTO t (id, name) VALUES (1, 'a') ON CONFLICT (id) DO UPDATE SET name = excluded.name`

	for _, dialect := range []int{SQLite, PostgreSQL} {
		got, notes := mustRewrite(t, sql, dialect, nil)

		if len(notes) != 0 {
			t.Errorf("dialect %d: expected no rewrite notes for already-native ON CONFLICT, got: %v", dialect, notes)
		}

		if !strings.Contains(got, "ON CONFLICT") {
			t.Errorf("dialect %d: expected ON CONFLICT preserved, got:\n%s", dialect, got)
		}
	}
}
