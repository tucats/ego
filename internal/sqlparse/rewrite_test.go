package sqlparse

import (
	"strings"
	"testing"

	"github.com/tucats/ego/internal/errors"
)

// mustRewrite parses sql as dialect, calls Rewrite (with lookup, which may
// be nil), and fails the test if either step errors. It returns the
// formatted result so callers can assert on the actual output text.
func mustRewrite(t *testing.T, sql string, dialect int, lookup UniqueKeyLookup) (string, []string) {
	t.Helper()

	p, err := New(sql, dialect)
	if err != nil {
		t.Fatalf("New: unexpected error: %v\nsql: %s", err, sql)
	}

	notes, err := p.Rewrite(lookup)
	if err != nil {
		t.Fatalf("Rewrite: unexpected error: %v\nsql: %s", err, sql)
	}

	return p.Format(), notes
}

func TestRewriteGeneratedKeySQLiteToPostgres(t *testing.T) {
	got, notes := mustRewrite(t, `CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT)`, PostgreSQL, nil)

	if !strings.Contains(got, "GENERATED BY DEFAULT AS IDENTITY") {
		t.Errorf("expected GENERATED BY DEFAULT AS IDENTITY in output, got:\n%s", got)
	}

	if strings.Contains(got, "AUTOINCREMENT") {
		t.Errorf("expected AUTOINCREMENT to be gone, got:\n%s", got)
	}

	if len(notes) == 0 {
		t.Errorf("expected at least one rewrite note")
	}

	// Round-trip: the rewritten PostgreSQL text must itself parse cleanly as
	// PostgreSQL and be a no-op under a second Rewrite pass.
	got2, notes2 := mustRewrite(t, got, PostgreSQL, nil)
	if got2 != got {
		t.Errorf("second Rewrite pass changed output:\n--- first ---\n%s\n--- second ---\n%s", got, got2)
	}

	if len(notes2) != 0 {
		t.Errorf("expected no notes on an already-PostgreSQL statement, got: %v", notes2)
	}
}

func TestRewriteGeneratedKeyPostgresToSQLite(t *testing.T) {
	for _, sql := range []string{
		`CREATE TABLE t (id SERIAL PRIMARY KEY, name TEXT)`,
		`CREATE TABLE t (id BIGSERIAL PRIMARY KEY, name TEXT)`,
		`CREATE TABLE t (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT)`,
		`CREATE TABLE t (id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name TEXT)`,
	} {
		got, _ := mustRewrite(t, sql, SQLite, nil)

		if !strings.Contains(got, "PRIMARY KEY AUTOINCREMENT") {
			t.Errorf("sql %q: expected PRIMARY KEY AUTOINCREMENT in output, got:\n%s", sql, got)
		}

		if !strings.Contains(got, "INTEGER") {
			t.Errorf("sql %q: expected INTEGER type in output, got:\n%s", sql, got)
		}

		if strings.Contains(got, "SERIAL") || strings.Contains(got, "IDENTITY") {
			t.Errorf("sql %q: expected no PostgreSQL-only syntax left, got:\n%s", sql, got)
		}
	}
}

func TestRewriteGeneratedKeyTableLevelPrimaryKey(t *testing.T) {
	// The PRIMARY KEY is written as a table-level constraint, not attached
	// to the column itself -- Rewrite must still find it, since sqlite3's
	// AUTOINCREMENT can only be expressed as a column-level constraint.
	got, notes := mustRewrite(t, `CREATE TABLE t (id SERIAL, name TEXT, PRIMARY KEY (id))`, SQLite, nil)

	if !strings.Contains(got, "AUTOINCREMENT") {
		t.Errorf("expected AUTOINCREMENT in output, got:\n%s", got)
	}

	if strings.Contains(got, "PRIMARY KEY (") {
		t.Errorf("expected the table-level PRIMARY KEY to be gone, got:\n%s", got)
	}

	found := false

	for _, n := range notes {
		if strings.Contains(n, "table level to column level") {
			found = true
		}
	}

	if !found {
		t.Errorf("expected a note about moving the PRIMARY KEY, got: %v", notes)
	}
}

func TestRewriteGeneratedKeyWithoutPrimaryKeyErrorsTowardSQLite(t *testing.T) {
	// PostgreSQL allows a GENERATED ... AS IDENTITY column that is not the
	// table's PRIMARY KEY; sqlite3 has no way to express that.
	p, err := New(`CREATE TABLE t (id INTEGER GENERATED ALWAYS AS IDENTITY, other_id INTEGER PRIMARY KEY)`, SQLite)
	if err != nil {
		t.Fatalf("New: unexpected error: %v", err)
	}

	_, err = p.Rewrite(nil)
	if err == nil {
		t.Fatalf("expected an error, got none")
	}

	ee, ok := err.(*errors.Error)
	if !ok {
		t.Fatalf("expected *errors.Error, got %T", err)
	}

	if !ee.Equal(errors.ErrSQLDialectRewrite) {
		t.Errorf("got error %v, want ErrSQLDialectRewrite", err)
	}
}

